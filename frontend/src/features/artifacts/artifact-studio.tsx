const CodeEditor = dynamic(() => import("@/components/editor/code-editor"), { ssr: false, loading: () => <Skeleton className="h-[420px]" /> });

export function ArtifactList() {
  const { data, isPending } = useArtifacts();
  const [q, setQ] = React.useState("");
  const rows = (data ?? []).filter((a) => a.title.toLowerCase().includes(q.toLowerCase()));
  return (
    <div className="mx-auto max-w-6xl space-y-6 px-4 py-8 md:px-8">
      <PageHeader icon={Archive} title="Artifact Studio" description="Reports and analyses generated by missions, workflows and the Data Lab — versioned, citable and exportable." actions={<Input placeholder="Search artifacts" value={q} onChange={(e) => setQ(e.target.value)} className="w-64" />} />
      {isPending ? <Skeleton className="h-64" /> : !rows.length ? (
        <Card><EmptyState icon={Archive} title="No artifacts yet" description="Run a research mission or save an analysis from the Data Lab to create one." action={<Button asChild><Link href="/research">Start research</Link></Button>} /></Card>
      ) : (
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {rows.map((a) => (
            <Link key={a.id} href={`/artifacts/${a.id}`} className="group rounded-2xl border border-line bg-surface p-4 shadow-card transition hover:-translate-y-px hover:border-[#c7d6fb] hover:shadow-pop">
              <div className="flex items-center gap-2">
                <div className="flex size-8 items-center justify-center rounded-lg bg-primary-soft text-primary">{a.kind === "analysis" ? <Sigma className="size-4" /> : <FileText className="size-4" />}</div>
                <Badge tone={a.kind === "analysis" ? "violet" : "blue"}>{a.kind}</Badge>
                <span className="ml-auto text-[11.5px] text-faint">v{a.current_version}</span>
              </div>
              <div className="mt-3 line-clamp-2 text-[14px] font-semibold leading-snug text-ink group-hover:text-primary-deep">{a.title}</div>
              <div className="mt-2 text-[12px] text-muted">Updated {timeAgo(a.updated_at)}</div>
            </Link>
          ))}
        </div>
      )}
    </div>
  );
}

export function ArtifactViewer({ id }: { id: string }) {
  const qc = useQueryClient();
  const router = useRouter();
  const { data: art, isPending, error } = useQuery({ queryKey: keys.artifact(id), queryFn: () => api.get<ArtifactDetail>(`/artifacts/${id}`) });
  const [version, setVersion] = React.useState<number | null>(null);
  const shown = version ?? art?.current_version ?? null;
  const ver = useQuery({
    queryKey: ["artifact-version", id, shown],
    queryFn: () => api.get<ArtifactVersion>(`/artifacts/${id}/versions/${shown}`),
    enabled: !!art && shown !== art.current_version,
  });
  const v = art && (shown === art.current_version ? art.latest : ver.data);
  const task = useQuery({ queryKey: keys.task(art?.task_id ?? ""), queryFn: () => api.get<Task>(`/tasks/${art!.task_id}`), enabled: !!art?.task_id });
  const [full, setFull] = React.useState(false);
  const [draft, setDraft] = React.useState<string | null>(null);
  const [citation, setCitation] = React.useState<Citation | null>(null);
  const [copied, setCopied] = React.useState(false);

  const save = useMutation({
    mutationFn: () => api.post<ArtifactVersion>(`/artifacts/${id}/versions`, { content: draft, note: "Edited in Artifact Studio" }),
    onSuccess: (nv) => {
      toast.success(`Saved version ${nv.version}`);
      setDraft(null);
      setVersion(null);
      void qc.invalidateQueries({ queryKey: keys.artifact(id) });
    },
    onError: (e) => toast.error((e as Error).message),
  });
  const remove = useMutation({ mutationFn: () => api.del(`/artifacts/${id}`), onSuccess: () => { void qc.invalidateQueries({ queryKey: keys.artifacts }); router.replace("/artifacts"); } });

  if (error) return <div className="p-6"><ErrorNote error={error} /></div>;
  if (isPending || !art) return <div className="space-y-3 p-6"><Skeleton className="h-14" /><Skeleton className="h-[60vh]" /></div>;

  const cites = v?.data.citations ?? [];
  const exportAs = async (fmt: string) => {
    try {
      const name = await download(`/artifacts/${id}/export?format=${fmt}&version=${shown}`, `artifact.${fmt}`);
      toast.success(`Downloaded ${name}`);
    } catch (e) {
      toast.error((e as Error).message);
    }
  };

  const body = v ? (
    <Tabs defaultValue="preview" className="flex min-h-0 flex-1 flex-col">
      <div className="flex flex-wrap items-center gap-2 border-b border-line px-5 py-2.5">
        <TabsList>
          <TabsTrigger value="preview"><FileText /> Preview</TabsTrigger>
          {!!v.data.tables?.length && <TabsTrigger value="data"><Sigma /> Data · {v.data.tables.length}</TabsTrigger>}
          <TabsTrigger value="sources">Sources · {cites.length}</TabsTrigger>
          <TabsTrigger value="edit">Edit</TabsTrigger>
        </TabsList>
        <div className="ml-auto flex items-center gap-1">
          {art.formats.map((f) => <Button key={f} variant="secondary" size="sm" onClick={() => exportAs(f)}><Download /> {f.toUpperCase()}</Button>)}
          <Button variant="ghost" size="icon-sm" aria-label="Copy markdown" onClick={async () => { await navigator.clipboard.writeText(v.content); setCopied(true); setTimeout(() => setCopied(false), 1500); }}>{copied ? <Check /> : <Copy />}</Button>
          <Button variant="ghost" size="icon-sm" aria-label={full ? "Exit full screen" : "Full screen"} onClick={() => setFull(!full)}>{full ? <Minimize2 /> : <Expand />}</Button>
        </div>
      </div>
      <TabsContent value="preview" className="nx-scroll min-h-0 flex-1 overflow-y-auto">
        <article className="mx-auto max-w-[820px] px-6 py-8">
          <h1 className="mb-6 text-[26px] font-semibold leading-tight tracking-[-0.025em] text-ink">{art.title}</h1>
          {v.data.verification && <VerificationStrip v={v.data.verification} />}
          {!!v.data.charts?.length && (
            <div className="mb-6 grid gap-3 md:grid-cols-2">{v.data.charts.map((c, i) => <ChartView key={i} spec={c} height={230} />)}</div>
          )}
          <Markdown content={v.content} onCite={(l) => { const c = cites.find((x) => x.label === l); if (c) setCitation(c); }} known={new Set([...cites.map((c) => c.label), ...(v.data.tables ?? []).map((t) => /\[(D\d+)\]/.exec(t.title)?.[1] ?? "")])} />
        </article>
      </TabsContent>
      <TabsContent value="data" className="nx-scroll min-h-0 flex-1 space-y-4 overflow-y-auto p-5">
        {v.data.tables?.map((t, i) => (
          <Card key={i} className="overflow-hidden">
            <div className="border-b border-line px-4 py-2 text-[13px] font-medium text-ink">{t.title}</div>
            <DataTable columns={t.columns} rows={t.rows} maxHeight={320} />
            {t.sql && <pre className="overflow-x-auto border-t border-line bg-surface-2 px-4 py-2 font-mono text-[11px] text-muted">{t.sql}</pre>}
          </Card>
        ))}
      </TabsContent>
      <TabsContent value="sources" className="nx-scroll min-h-0 flex-1 overflow-y-auto p-5">
        {!cites.length ? <EmptyState icon={FileText} title="No citations" description="This artifact does not cite external evidence." /> : (
          <div className="space-y-2">
            {cites.map((c) => (
              <button key={c.label} onClick={() => setCitation(c)} className="flex w-full items-start gap-3 rounded-xl border border-line p-3 text-left hover:border-primary/40">
                <span className="rounded-md bg-primary-soft px-1.5 py-0.5 font-mono text-[11px] font-semibold text-primary-deep">{c.label}</span>
                <div className="min-w-0">
                  <div className="text-[13px] font-medium text-ink">{c.title || c.filename}</div>
                  <div className="text-[11.5px] text-faint">{c.kind === "web" ? `${c.domain} · retrieved ${formatDateTime(c.retrieved_at)}` : `${c.filename}${c.page ? ` · page ${c.page}` : ""}`}</div>
                  <p className="mt-1 line-clamp-2 text-[12.5px] text-ink-2">{c.excerpt}</p>
                </div>
              </button>
            ))}
          </div>
        )}
      </TabsContent>
      <TabsContent value="edit" className="flex min-h-0 flex-1 flex-col">
        <div className="min-h-0 flex-1"><CodeEditor language="markdown" value={draft ?? v.content} onChange={setDraft} height="100%" /></div>
        <div className="flex items-center gap-2 border-t border-line px-5 py-3">
          <span className="text-[12px] text-muted">Saving creates version {art.current_version + 1}; earlier versions stay available.</span>
          <Button className="ml-auto" disabled={draft === null || save.isPending} onClick={() => save.mutate()}>{save.isPending ? <Loader2 className="animate-spin" /> : <Save />} Save new version</Button>
        </div>
      </TabsContent>
    </Tabs>
  ) : <Skeleton className="m-6 h-96" />;

  return (
    <div className={cn("flex h-full flex-col lg:flex-row", full && "fixed inset-0 z-40 bg-bg")}>
      {!full && (
        <aside className="nx-scroll w-full shrink-0 space-y-5 overflow-y-auto border-b border-line bg-surface p-5 lg:w-[320px] lg:border-b-0 lg:border-r">
          <Link href="/artifacts" className="text-[12.5px] text-muted hover:text-primary">← All artifacts</Link>
          <div>
            <Badge tone={art.kind === "analysis" ? "violet" : "blue"}>{art.kind}</Badge>
            <h2 className="mt-2 text-[16px] font-semibold leading-snug text-ink">{art.title}</h2>
            <div className="mt-1 text-[12px] text-faint">Created {formatDateTime(art.created_at)}</div>
          </div>
          {task.data && (
            <div className="rounded-xl border border-line bg-surface-2 p-3">
              <div className="text-[11px] font-semibold uppercase tracking-[0.08em] text-faint">Instructions</div>
              <p className="mt-1.5 text-[13px] leading-relaxed text-ink-2">{task.data.prompt}</p>
              <Link href={`/missions/${task.data.id}`} className="mt-2 inline-block text-[12.5px] font-medium text-primary hover:underline">View execution in Mission Control →</Link>
            </div>
          )}
          <div>
            <div className="mb-2 flex items-center gap-1.5 text-[11px] font-semibold uppercase tracking-[0.08em] text-faint"><History className="size-3.5" /> Versions</div>
            <Select ariaLabel="Version" value={String(shown)} onValueChange={(x) => { setVersion(Number(x)); setDraft(null); }} className="w-full" options={[...art.versions].reverse().map((x) => ({ value: String(x.version), label: `Version ${x.version}${x.version === art.current_version ? " (latest)" : ""}`, hint: `${x.note} · ${timeAgo(x.created_at)}` }))} />
          </div>
          <Button variant="danger-ghost" size="sm" onClick={() => { if (window.confirm("Delete this artifact and all versions?")) remove.mutate(); }}><Trash2 /> Delete artifact</Button>
        </aside>
      )}
      <div className="flex min-h-[70vh] min-w-0 flex-1 flex-col bg-surface lg:min-h-0">{body}</div>
      <CitationDialog citation={citation} onClose={() => setCitation(null)} />
    </div>
  );
}

function VerificationStrip({ v }: { v: Record<string, any> }) { // eslint-disable-line @typescript-eslint/no-explicit-any
  return (
    <div className="mb-6 flex flex-wrap items-center gap-3 rounded-xl border border-[#c6f1df] bg-success-soft/60 px-4 py-2.5 text-[12.5px]">
      <ShieldCheck className="size-4 text-success" />
      <span className="font-medium text-ink">Verified against retrieved evidence</span>
      <span className="text-[#047857]">{v.supported} supported</span>
      <span className="text-[#b45309]">{v.weak} weak</span>
      <span className="text-[#b91c1c]">{v.unsupported} unsupported</span>
      <span className="text-muted">of {v.claims_checked} cited claims</span>
    </div>
  );
}
